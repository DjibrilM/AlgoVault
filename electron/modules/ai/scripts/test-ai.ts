import assert from 'node:assert'
import { convertArrayToReadableStream } from '@ai-sdk/provider-utils/test'
import { MockLanguageModelV4 } from 'ai/test'
import {
  AI_CHANNELS,
  AI_MODEL_PRESETS,
  groupModelsByProvider,
  type AiStreamEvent,
} from '../../../../src/shared/types/ai.ts'
import { MainModule } from '../../../main.module.ts'

class MockIpcMain {
  handlers = new Map<string, (...args: unknown[]) => unknown>()

  handle(channel: string, listener: (...args: unknown[]) => unknown): void {
    this.handlers.set(channel, listener)
  }

  removeHandler(channel: string): void {
    this.handlers.delete(channel)
  }

  async invoke<T = unknown>(channel: string, ...args: unknown[]): Promise<T> {
    const handler = this.handlers.get(channel)
    if (!handler) {
      throw new Error(`No handler registered for channel: ${channel}`)
    }
    return (await handler({}, ...args)) as T
  }
}

const ZERO_USAGE = {
  inputTokens: { total: 10, noCache: 10, cacheRead: 0, cacheWrite: 0 },
  outputTokens: { total: 10, text: 10, reasoning: 0 },
}

function makeTextStream(text: string, reasoning = '') {
  return convertArrayToReadableStream([
    { type: 'stream-start' as const, warnings: [] },
    ...(reasoning
      ? [
          { type: 'reasoning-start' as const, id: 'r1' },
          { type: 'reasoning-delta' as const, id: 'r1', delta: reasoning },
          { type: 'reasoning-end' as const, id: 'r1' },
        ]
      : []),
    { type: 'text-start' as const, id: 't1' },
    { type: 'text-delta' as const, id: 't1', delta: text },
    { type: 'text-end' as const, id: 't1' },
    {
      type: 'finish' as const,
      finishReason: { unified: 'stop' as const, raw: 'stop' },
      usage: ZERO_USAGE,
    },
  ])
}

function makeToolCallStream(toolCallId: string, toolName: string, inputObj: unknown) {
  return convertArrayToReadableStream([
    { type: 'stream-start' as const, warnings: [] },
    {
      type: 'tool-call' as const,
      toolCallId,
      toolName,
      input: JSON.stringify(inputObj),
    },
    {
      type: 'finish' as const,
      finishReason: { unified: 'tool-calls' as const, raw: 'tool_calls' },
      usage: ZERO_USAGE,
    },
  ])
}

async function main() {
  console.log('Testing AiModule multi-agent orchestration with MockLanguageModelV4...\n')

  const mockIpc = new MockIpcMain()
  const events: AiStreamEvent[] = []
  let streamCallIndex = 0
  let generateCallIndex = 0

  const scriptedChallengeSet = {
    categoryTitle: 'Sliding Window Mastery',
    categoryDescription: 'Custom sliding window challenges generated by Challenge Architect.',
    challenges: [
      {
        title: 'Max Subarray Window Sum',
        difficulty: 'Medium' as const,
        style: 'Implementation' as const,
        description:
          '### Max Subarray Window Sum\n\nGiven an integer array `nums` and window size `k`, return the maximum contiguous subarray sum.',
        constraints: ['$1 \\le k \\le \\text{nums.length} \\le 10^5$'],
        hints: [
          'Maintain a running window sum as you slide by one element.',
          'Subtract the outgoing element at `i - k`.',
        ],
        examples: [
          {
            input: 'nums = [2, 1, 5, 1, 3, 2], k = 3',
            output: '9',
            explanation: 'Subarray [5, 1, 3] has the maximum sum of 9.',
          },
        ],
        initialSolutions: {
          typescript: 'function maxWindowSum(nums: number[], k: number): number {\n  return 0;\n}',
          javascript: 'function maxWindowSum(nums, k) {\n  return 0;\n}',
          python: 'def max_window_sum(nums: list[int], k: int) -> int:\n    return 0',
          cpp: 'int maxWindowSum(vector<int>& nums, int k) {\n    return 0;\n}',
        },
        testCases: [
          { input: 'nums = [2, 1, 5, 1, 3, 2], k = 3', expected: '9' },
          { input: 'nums = [2, 3, 4, 1, 5], k = 2', expected: '7', hidden: true },
        ],
      },
    ],
  }

  const mockModel = new MockLanguageModelV4({
    doGenerate: async (options) => {
      generateCallIndex += 1
      const systemText = options.prompt
        .filter((m) => m.role === 'system')
        .map((m) => (typeof m.content === 'string' ? m.content : ''))
        .join('\n')

      // Challenge Architect subagent uses Output.object -> doGenerate
      if (systemText.includes("AlgoVault's Challenge Architect subagent")) {
        return {
          finishReason: { unified: 'stop', raw: 'stop' },
          usage: ZERO_USAGE,
          content: [{ type: 'text', text: JSON.stringify(scriptedChallengeSet) }],
          warnings: [],
        }
      }

      // Connection test
      return {
        finishReason: { unified: 'stop', raw: 'stop' },
        usage: ZERO_USAGE,
        content: [{ type: 'text', text: 'OK' }],
        warnings: [],
      }
    },
    doStream: async (options) => {
      streamCallIndex += 1
      const systemText = options.prompt
        .filter((m) => m.role === 'system')
        .map((m) => (typeof m.content === 'string' ? m.content : ''))
        .join('\n')

      // Catalog Analyst subagent: call listCategories -> then summarize
      if (systemText.includes("AlgoVault's Catalog Analyst subagent")) {
        const hasToolResult = options.prompt.some((m) => m.role === 'tool')
        if (!hasToolResult) {
          return { stream: makeToolCallStream('tc-cat-1', 'listCategories', {}) }
        }
        return {
          stream: makeTextStream(
            'Found 20 existing DSA categories including Sliding Window. No duplicate title "Max Subarray Window Sum".'
          ),
        }
      }

      // Master Agent turn 1 (Draft Shaping): updateDraft -> text response
      if (streamCallIndex === 1) {
        return {
          stream: makeToolCallStream('tc-m-1', 'updateDraft', {
            topic: 'Sliding Window',
            category: 'Algorithms',
            contentType: 'Practice Questions',
            difficulty: 'Medium',
            questionCount: 1,
            questionStyle: 'Implementation',
          }),
        }
      }
      if (streamCallIndex === 2) {
        return {
          stream: makeTextStream(
            'Everything is set for 1 Medium Implementation Sliding Window problem. Ready to generate?',
            'Updated all 6 draft specification fields.'
          ),
        }
      }

      // Master Agent turn 2 (Orchestrated Multi-Agent Generation):
      // Step 3: consultCatalogAnalyst -> Step 5 (after catalog analyst): invokeChallengeArchitect
      // -> Step 6: verifyChallengeSet -> Step 7: saveChallengeSet -> Step 8: final summary
      const toolResults = options.prompt.filter((m) => m.role === 'tool')
      if (toolResults.length === 0) {
        return {
          stream: makeToolCallStream('tc-m-2', 'consultCatalogAnalyst', {
            task: 'Check existing Sliding Window categories and titles',
          }),
        }
      }
      if (toolResults.length === 1) {
        return {
          stream: makeToolCallStream('tc-m-3', 'invokeChallengeArchitect', {
            topic: 'Sliding Window',
            category: 'Algorithms',
            contentType: 'Practice Questions',
            difficulty: 'Medium',
            questionCount: 1,
            questionStyle: 'Implementation',
          }),
        }
      }
      if (toolResults.length === 2) {
        return {
          stream: makeToolCallStream('tc-m-4', 'verifyChallengeSet', { strict: true }),
        }
      }
      if (toolResults.length === 3) {
        return {
          stream: makeToolCallStream('tc-m-5', 'saveChallengeSet', {}),
        }
      }

      return {
        stream: makeTextStream('All **1** Sliding Window challenge has been crafted, verified, and saved!'),
      }
    },
  })

  const mainModule = await MainModule.bootstrap({
    ipcMain: mockIpc as unknown as Electron.IpcMain,
    database: { dbPath: ':memory:', synchronize: true },
    ai: {
      modelResolver: async () => ({
        model: mockModel,
        status: {
          configured: true,
          source: 'settings',
          provider: 'gateway',
          modelId: 'mock/test-model',
          baseUrl: '',
          hasApiKey: true,
          maskedApiKey: 'mock••••1234',
        },
      }),
      onStreamEvent: (ev) => events.push(ev),
    },
  })

  try {
    // 1. Test saving & masking AI provider settings in SQLite + preserving per-provider keys across switches
    const savedStatus = await mockIpc.invoke<{
      configured: boolean
      maskedApiKey: string | null
      provider: string
    }>(AI_CHANNELS.SAVE_CONFIG, {
      provider: 'openai',
      modelId: 'gpt-4.1-mini',
      baseUrl: '',
      apiKey: 'sk-test-secret-key-9876',
    })
    assert.strictEqual(savedStatus.configured, true)
    assert.strictEqual(savedStatus.provider, 'openai')
    assert.strictEqual(savedStatus.maskedApiKey, 'sk-t••••9876', 'API key should be masked')

    await mockIpc.invoke(AI_CHANNELS.SAVE_CONFIG, {
      provider: 'gateway',
      modelId: 'openai/gpt-5',
    })
    const restoredOpenAi = await mockIpc.invoke<{
      configured: boolean
      maskedApiKey: string | null
      provider: string
    }>(AI_CHANNELS.SAVE_CONFIG, {
      provider: 'openai',
      modelId: 'gpt-5-mini',
    })
    assert.strictEqual(restoredOpenAi.provider, 'openai')
    assert.strictEqual(
      restoredOpenAi.maskedApiKey,
      'sk-t••••9876',
      'Switching back to a provider must preserve its stored API key'
    )
    console.log('  ✔ SQLite AI config save + per-provider key preservation passed')

    // 2. Test model listing + provider grouping + connection check + model override
    const models = await mockIpc.invoke<Array<{ id: string }>>(AI_CHANNELS.LIST_MODELS)
    assert.ok(models.length >= 3, 'Expected curated model options for active provider')

    const gatewayGroups = groupModelsByProvider(AI_MODEL_PRESETS.gateway)
    assert.ok(
      gatewayGroups.some((g) => g.provider === 'anthropic' && g.models.length > 0),
      'Expected Anthropic provider group'
    )
    assert.ok(
      gatewayGroups.some((g) => g.provider === 'openai' && g.models.length > 0),
      'Expected OpenAI provider group'
    )

    const conn = await mockIpc.invoke<{ ok: boolean; reply?: string }>(AI_CHANNELS.TEST_CONNECTION)
    assert.strictEqual(conn.ok, true)
    assert.strictEqual(conn.reply, 'OK')
    console.log('  ✔ Model listing + Connection test passed')

    // 3. Test Turn 1: Master Agent shapes draft
    const turn1 = await mainModule.aiModule.service.runStudioTurn({
      runId: 'run-1',
      prompt: 'Give me 1 medium implementation problem on sliding window',
      messages: [],
      draft: null,
    })
    assert.strictEqual(turn1.draft?.topic, 'Sliding Window')
    assert.strictEqual(turn1.draft?.readyToGenerate, true)
    assert.ok(events.some((e) => e.runId === 'run-1' && e.type === 'draft-updated'))
    console.log('  ✔ Turn 1 Master Agent draft shaping + streaming passed')

    // 4. Test Turn 2: Master Agent delegates Catalog Analyst -> Challenge Architect -> Verifier -> SQLite
    const turn2 = await mockIpc.invoke<{
      text: string
      draft: { generated: boolean } | null
      generatedQuestions?: Array<{ title: string }>
      generatedTarget?: { name: string } | null
      generatedProblemIds?: number[]
    }>(AI_CHANNELS.RUN_STUDIO_TURN, {
      runId: 'run-2',
      prompt: 'Yes, go ahead',
      messages: [
        { id: 'u1', from: 'user', content: 'Give me 1 medium implementation problem on sliding window' },
        { id: 'a1', from: 'assistant', content: turn1.text },
      ],
      draft: turn1.draft,
      forceGenerate: true,
    })

    assert.strictEqual(turn2.draft?.generated, true)
    assert.strictEqual(turn2.generatedQuestions?.length, 1)
    assert.strictEqual(turn2.generatedQuestions?.[0].title, 'Max Subarray Window Sum')
    assert.strictEqual(turn2.generatedTarget?.name, 'Sliding Window Mastery')
    assert.ok((turn2.generatedProblemIds?.length ?? 0) === 1)
    assert.ok(generateCallIndex >= 2, 'Expected Challenge Architect + connection check calls')

    // Verify subagent stage events were streamed
    const run2Agents = new Set(
      events
        .filter((e): e is Extract<AiStreamEvent, { type: 'agent-stage' }> => e.runId === 'run-2' && e.type === 'agent-stage')
        .map((e) => e.agent)
    )
    assert.ok(run2Agents.has('master'), 'Expected master agent stage event')
    assert.ok(run2Agents.has('catalog-analyst'), 'Expected catalog-analyst subagent event')
    assert.ok(run2Agents.has('challenge-architect'), 'Expected challenge-architect subagent event')
    assert.ok(run2Agents.has('challenge-verifier'), 'Expected challenge-verifier tool event')

    // Verify persisted inside SQLite database
    const workspaceData = await mainModule.codeTestModule.service.getWorkspaceData()
    const createdChallenge = workspaceData.challenges.find((c) => c.title === 'Max Subarray Window Sum')
    assert.ok(createdChallenge, 'Challenge should be saved into SQLite database')
    assert.ok(createdChallenge.initialSolutions?.python.includes('def max_window_sum'))

    console.log('  ✔ Turn 2 Master -> Catalog Analyst -> Challenge Architect -> Verifier -> SQLite passed')
    console.log('\nAll AiModule integration checks passed!')
  } finally {
    await mainModule.onModuleDestroy()
  }
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
